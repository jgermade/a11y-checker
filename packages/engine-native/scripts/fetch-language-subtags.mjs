// Extracts the primary language subtags (Type: language) from the IANA Language
// Subtag Registry into src/data/language-subtags.ts: `pnpm fetch:languages`.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const REGISTRY =
  'https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry';
const text = await (await fetch(REGISTRY)).text();
const date = /^File-Date: (.+)$/m.exec(text)?.[1] ?? 'unknown';
const subtags = text
  .split('\n%%\n')
  .filter((record) => /^Type: language$/m.test(record))
  .map((record) => /^Subtag: (.+)$/m.exec(record)?.[1]?.toLowerCase())
  .filter((subtag) => subtag && !subtag.includes('..')); // skip private-use ranges (qaa..qtz)

const out = fileURLToPath(new URL('../src/data/language-subtags.ts', import.meta.url));
await writeFile(
  out,
  `// Generated by scripts/fetch-language-subtags.mjs from the IANA Language Subtag Registry
// (File-Date: ${date}). Do not edit by hand.
// prettier-ignore
export const LANGUAGE_SUBTAGS = new Set(
  ${JSON.stringify(subtags.join(' '))}.split(' '),
);

/** Private-use primary language subtags (qaa..qtz) are valid too. */
export const isPrivateUseLanguage = (subtag: string): boolean => /^q[a-t][a-z]$/.test(subtag);
`,
);
console.log(`${subtags.length} language subtags (registry ${date})`);
