// Writes the ACT implementation report (EARL) and a benchmark of the three engines on
// the same W3C test cases. Run with: pnpm --filter @a11y-checker/engine-native act:report
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import pkg from '../package.json' with { type: 'json' };
import { RULES } from '../src/index.js';
import { consistency, runActSuite, type CaseResult, type EngineName } from './act/harness.js';

const OUT = (name: string) => fileURLToPath(new URL(`../${name}`, import.meta.url));
const ENGINES: { id: EngineName; label: string }[] = [
  { id: 'native', label: `a11y-checker native ${pkg.version}` },
  { id: 'axe', label: 'axe-core' },
  { id: 'ibm', label: 'IBM Equal Access' },
];

type Verdict = 'consistent' | 'partial' | 'inconsistent' | 'untested';

function verdictFor(results: CaseResult[], engine: EngineName): Verdict {
  const verdicts = results.map((r) =>
    consistency(r.testcase.expected, r.outcomes[engine] ?? 'inapplicable'),
  );
  // An implementation that never fails a failed example does not implement the rule.
  const failsSomething = results.some(
    (r) => r.testcase.expected === 'failed' && r.outcomes[engine] === 'failed',
  );
  if (!failsSomething) return 'untested';
  if (verdicts.includes('inconsistent')) return 'inconsistent';
  return verdicts.includes('partial') ? 'partial' : 'consistent';
}

const EARL_OUTCOME = {
  passed: 'earl:passed',
  failed: 'earl:failed',
  cantTell: 'earl:cantTell',
  inapplicable: 'earl:inapplicable',
} as const;

describe.skipIf(process.env.A11Y_ACT_REPORT !== '1')('ACT report', () => {
  it('writes the EARL report and the benchmark', { timeout: 600_000 }, async () => {
    const results = await runActSuite(ENGINES.map((e) => e.id));
    const byRule = new Map<string, CaseResult[]>();
    for (const result of results) {
      const list = byRule.get(result.testcase.ruleId) ?? [];
      list.push(result);
      byRule.set(result.testcase.ruleId, list);
    }

    // EARL (JSON-LD), in the shape the ACT Rules Community uses for implementation reports.
    const earl = {
      '@context': 'https://act-rules.github.io/earl-context.json',
      '@graph': results.map(({ testcase, outcomes }) => {
        const rule = RULES.find((r) => r.actRuleIds.includes(testcase.ruleId));
        return {
          '@type': 'TestSubject',
          source: testcase.url,
          assertions: [
            {
              '@type': 'Assertion',
              mode: 'earl:automatic',
              assertedBy: {
                '@type': 'Assertor',
                name: 'a11y-checker native',
                version: pkg.version,
              },
              test: { '@type': 'TestCase', title: rule?.id ?? testcase.ruleId },
              result: {
                '@type': 'TestResult',
                outcome: EARL_OUTCOME[outcomes.native ?? 'inapplicable'],
              },
            },
          ],
        };
      }),
    };
    await writeFile(OUT('act-report.earl.json'), `${JSON.stringify(earl, null, 2)}\n`);

    const rows = [...byRule.entries()].map(([ruleId, cases]) => {
      const name = cases[0]?.testcase.ruleName ?? ruleId;
      const cells = ENGINES.map((e) => verdictFor(cases, e.id));
      return { ruleId, name, count: cases.length, cells };
    });
    const icon: Record<Verdict, string> = {
      consistent: '✅ consistent',
      partial: '🟡 partial',
      inconsistent: '❌ inconsistent',
      untested: '⚪ not reported',
    };
    const lines = [
      '# ACT benchmark',
      '',
      'Generated by `pnpm --filter @a11y-checker/engine-native act:report`. Each engine ran',
      'every [W3C ACT](https://www.w3.org/WAI/standards-guidelines/act/rules/) test case of',
      'the rules implemented by the native engine, as a top-level page in Chromium, with its',
      'default rules (WCAG 2.2 AAA and best practices enabled).',
      '',
      '- **consistent**: every test case gives the expected outcome.',
      '- **partial**: some test cases are "can\'t tell" (left for manual review).',
      '- **inconsistent**: some passed or inapplicable example fails, or a failed one passes.',
      '- **not reported**: the engine fails none of the failed examples (no rule mapped to',
      '  this ACT rule, or the rule is disabled by default).',
      '',
      'Results can differ from the official implementation reports that each tool',
      'publishes, because of this environment: the network is blocked, so web fonts do not',
      'load (one 2ee8b8 example uses the Material Icons font), and `.xml` test cases are',
      'served as `application/xml`, as on w3.org. Engines other than the native one are run',
      'with their default rule selection, through the a11y-checker SDK.',
      '',
      `| ACT rule | Test cases | ${ENGINES.map((e) => e.label).join(' | ')} |`,
      `| --- | --- | ${ENGINES.map(() => '---').join(' | ')} |`,
      ...rows.map(
        (r) =>
          `| [${r.name}](https://www.w3.org/WAI/standards-guidelines/act/rules/${r.ruleId}/) (\`${r.ruleId}\`) | ${r.count} | ${r.cells.map((c) => icon[c]).join(' | ')} |`,
      ),
      '',
    ];
    await writeFile(OUT('ACT-REPORT.md'), lines.join('\n'));
    expect(rows.every((r) => r.cells[0] === 'consistent')).toBe(true);
  });
});
